# Teste de fumaça no navegador: python3 tests/e2e.py  (usa Chrome via Playwright)
import asyncio, os
from playwright.async_api import async_playwright
URL = 'file://' + os.path.abspath('index.html'); OUT = '/tmp/shots'; os.makedirs(OUT, exist_ok=True)
async def main():
    fails = []
    def ok(c, m):
        print(('OK   ' if c else 'FAIL ') + m); (not c) and fails.append(m)
    async with async_playwright() as p:
        b = await p.chromium.launch(executable_path='/usr/bin/google-chrome', args=['--no-sandbox', '--allow-file-access-from-files'])
        for w, h in [(390, 780), (360, 640), (1366, 768)]:
            pg = await b.new_page(viewport={'width': w, 'height': h}); errs = []
            pg.on('pageerror', lambda e: errs.append(str(e))); pg.on('console', lambda m: m.type == 'error' and errs.append(m.text))
            await pg.goto(URL); await pg.wait_for_timeout(300)
            ok('Crie sua organização'.lower() in (await pg.locator('#main').inner_text()).lower(), f'{w}: começa no assistente')
            await pg.fill('#su-nome', 'Pantera Teste'); await pg.click('[data-act=lg][data-k=s][data-id="🦅"]'); await pg.click('[data-act=lg][data-k=f][data-id=hex]')
            await pg.set_input_files('#logo-file', '/tmp/logo_test.png'); await pg.wait_for_timeout(400)
            ok(await pg.locator('.lg-prev .logo.img').count() == 1, f'{w}: logo com imagem enviada')
            await pg.screenshot(path=f'{OUT}/setup1_{w}.png')
            await pg.click('[data-act=su-next]'); ok('onde começar'.lower() in (await pg.locator('#main').inner_text()).lower(), f'{w}: escolha do jogo inicial')
            await pg.click('[data-act=su-game][data-id=cs2]'); await pg.click('[data-act=su-game][data-id=lol]'); await pg.click('[data-act=su-go]')
            ok('Escolha a estrela'.lower() in (await pg.locator('#main').inner_text()).lower(), f'{w}: escolha da estrela')
            await pg.click('[data-act=su-convite]:not([disabled])'); await pg.wait_for_timeout(100)
            await pg.screenshot(path=f'{OUT}/setup3_{w}.png')
            await pg.click('[data-act=su-sem]'); await pg.wait_for_timeout(100)
            ok('Pantera Teste'.lower() in (await pg.locator('#top').inner_text()).lower(), f'{w}: nome da org no cabeçalho')
            ok(await pg.locator('#top .logo.img').count() == 1, f'{w}: logo com imagem no cabeçalho')
            await pg.reload(); await pg.wait_for_timeout(200); ok(await pg.locator('#top .logo.img').count() == 1, f'{w}: imagem do logo persiste após recarregar')
            await pg.click('[data-act=game][data-id=cs2]'); ok('🔒'.lower() in (await pg.locator('#games').inner_text()).lower(), f'{w}: outro jogo começa trancado')
            await pg.click('[data-act=tab][data-id=elenco]'); ok('Abrir um time aqui custa'.lower() in (await pg.locator('#main').inner_text()).lower(), f'{w}: jogo trancado mostra como abrir')
            await pg.click('[data-act=tab][data-id=org]')
            await pg.click('[data-act=game][data-id=lol]')
            await pg.click('[data-act=tab][data-id=mercado]')
            ok(await pg.locator('#main .slot').count() > 0, f'{w}: mercado lista jogadores')
            await pg.click('[data-act=mpay]'); await pg.click('[data-act=masc]')
            for _ in range(5): await pg.locator('[data-act=contratar]:not([disabled])').first.click()
            await pg.click('[data-act=tab][data-id=elenco]')
            filled = await pg.locator('#main .slot .ovr').count()
            ok(filled >= 5, f'{w}: 5+ contratados no elenco ({filled})')
            await pg.screenshot(path=f'{OUT}/elenco_{w}.png')
            await pg.click('[data-act=tab][data-id=estrutura]'); await pg.locator('[data-act=infra]:not([disabled])').first.click()
            await pg.screenshot(path=f'{OUT}/estrutura_{w}.png')
            await pg.click('[data-act=tab][data-id=org]'); await pg.click('[data-act=avancar][data-n="4"]')
            ok('Semana 5'.lower() in (await pg.locator('#top').inner_text()).lower(), f'{w}: avançou 4 semanas')
            await pg.screenshot(path=f'{OUT}/org_{w}.png')
            await pg.click('[data-act=proximo]')
            await pg.click('[data-act=tab][data-id=calendario]'); ct = (await pg.locator('#main').inner_text()).lower()
            ok('próxima partida' in ct and 'agenda' in ct and 'fase regular' in ct, f'{w}: calendário mostra trilha, próxima partida e agenda')
            await pg.screenshot(path=f'{OUT}/calendario_{w}.png', full_page=False)
            await pg.click('[data-act=tab][data-id=ligas]'); txt = (await pg.locator('#main').inner_text()).lower()
            ok('rodada' in txt and 'seus últimos jogos' in txt, f'{w}: ligas mostra rodada e jogos do usuário')
            await pg.screenshot(path=f'{OUT}/ligas_{w}.png')
            await pg.click('[data-act=time]') if await pg.locator('[data-act=time]').count() else None
            antes = await pg.locator('#top').inner_text()
            await pg.reload(); await pg.wait_for_timeout(200)
            ok(antes == await pg.locator('#top').inner_text(), f'{w}: save persiste após recarregar')
            await pg.click('[data-act=game][data-id=lol]')
            for gid in ['ff', 'r6', 'fifa', 'wr']:
                ok(await pg.locator(f'[data-act=game][data-id={gid}]').count() == 1, f'{w}: jogo {gid} aparece no seletor')
            sw = await pg.evaluate('document.documentElement.scrollWidth <= window.innerWidth')
            ok(sw, f'{w}: sem rolagem horizontal'); ok(not errs, f'{w}: console limpo {errs[:2]}')
            await pg.close()
        await b.close()
    print('FALHAS:', len(fails)); raise SystemExit(1 if fails else 0)
asyncio.run(main())
